problems = []
for f in F:
    dur = round(sum(s[0] for s in f['shots']), 3)
    if abs(dur - 90) > 0.01: problems.append(f"{f['id']}: shots total {dur}s, not 90")
    prev = -1
    for (a, b, text, tone) in f['lines']:
        w = len(re.findall(r"[A-Za-z0-9']+", text))
        if a < prev + 0.3: problems.append(f"{f['id']}: line at {a} overlaps the previous one")
        if w * 60 / 165 + 0.3 > b - a: problems.append(f"{f['id']}: '{text}' needs {w * 60 / 165 + 0.3:.1f}s, window {b - a:.1f}s")
        if b > dur: problems.append(f"{f['id']}: line ends after the film")
        prev = b
    t, shots = 0.0, []
    for d, s in f['shots']: shots.append({'start': round(t, 3), 'end': round(t + d, 3), 'dur': d, 'direction': s}); t += d
    f2 = {k: v for k, v in f.items() if k not in ('shots', 'lines')}
    f2.update(duration=90, fps=24, shots=shots, narration=[{'id': f"N{i+1}", 'start': a, 'end': b, 'text': x, 'tone': y} for i, (a, b, x, y) in enumerate(f['lines'])])
    d = os.path.join(ROOT, 'films', 'showcase', f['id']); os.makedirs(d, exist_ok=True)
    json.dump(f2, open(os.path.join(d, 'story.json'), 'w'), indent=1, ensure_ascii=False)
    design, persona = f['narrator']
    json.dump({'film': f['id'], 'duration': 90, 'takes': 3, 'profile': persona, 'persona': persona,
               'lines': [{'id': f"N{i+1}", 'text': x, 'start': a, 'end': b, 'tone': y, 'wpm': [105, 175]} for i, (a, b, x, y) in enumerate(f['lines'])],
               'omni': {'design': design, 'num_step': 24, 'ref_text': 'Long ago, when the hills were young, the lanterns of the valley were lit by hand, one by one, every single evening.'}},
              open(os.path.join(ROOT, 'voice', 'jobs', f"{f['id']}.json"), 'w'), indent=1, ensure_ascii=False)
print('\n'.join(problems) if problems else f'{len(F)} films ok')
